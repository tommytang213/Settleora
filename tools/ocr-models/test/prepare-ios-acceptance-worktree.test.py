"""Real Git isolation contracts; no SDK, device, provider, or native build."""
from pathlib import Path
import importlib.util
import os
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[3]
SPEC = importlib.util.spec_from_file_location(
    "ios_acceptance_worktree", ROOT / "tools/ocr-models/prepare-ios-acceptance-worktree.py")
MODULE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(MODULE)


class IsolationTest(unittest.TestCase):
    def setUp(self):
        # Git redirection overrides -C. Isolate the whole test process before
        # fixture setup, including in-process MODULE calls and hosted children.
        env = {key: value for key, value in os.environ.items()
               if not key.startswith("GIT_")}
        env.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull)
        git_environment = patch.dict(os.environ, env, clear=True)
        git_environment.start()
        self.addCleanup(git_environment.stop)
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        self.repo = self.root / "source"
        self.runner_temp = self.root / "runner-temp"
        self.repo.mkdir()
        self.runner_temp.mkdir()
        self.git("init", "--quiet")
        self.paths = [
            "apps/mobile/pubspec.lock", "apps/mobile/lib/parser.dart",
            "apps/mobile/ios/Flutter/Debug.xcconfig",
            "apps/mobile/ios/Flutter/Release.xcconfig",
            "apps/mobile/ios/Runner.xcodeproj/project.pbxproj",
            "apps/mobile/ios/Runner.xcworkspace/contents.xcworkspacedata",
            "apps/mobile/ios/OtherTrackedFile",
        ]
        for name in self.paths:
            p = self.repo / name
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text("source\n")
        self.git("add", ".")
        self.git("-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
                 "commit", "--quiet", "-m", "fixture", "--no-gpg-sign")
        self.sha = self.git("rev-parse", "HEAD").strip()
        self.target = self.runner_temp / MODULE.DIRECTORY

    def git(self, *args, repo=None):
        return subprocess.check_output(
            ["git", "--no-optional-locks", "-C", str(repo or self.repo), *args],
            stderr=subprocess.DEVNULL, text=True)

    def test_exact_detached_source_and_mutations_do_not_dirty_capture_checkout(self):
        self.assertEqual({key: value for key, value in os.environ.items()
                          if key.startswith("GIT_")},
                         {"GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": os.devnull})
        result = MODULE.prepare(self.repo, self.runner_temp, self.sha)
        self.assertEqual(result, self.target)
        self.assertEqual(self.git("rev-parse", "HEAD", repo=result).strip(), self.sha)
        self.assertEqual(self.git("branch", "--show-current", repo=result), "")
        for name in self.paths:
            self.assertEqual((result / name).read_bytes(), (self.repo / name).read_bytes())
        # Model CocoaPods/Flutter edits, including the unknown tracked remainder.
        for name in self.paths[2:]:
            (result / name).write_text("generated by simulator dependency/test flow\n")
        self.assertNotEqual(self.git("status", "--porcelain", repo=result), "")
        self.assertEqual(self.git("status", "--porcelain"), "")
        self.assertEqual(MODULE.verify(self.repo, self.runner_temp, self.sha), result)
        # The unchanged capture helper still sees a genuinely clean source.
        spec = importlib.util.spec_from_file_location(
            "failure_capture", ROOT / "tools/ocr-models/package-failure-capture.py")
        capture = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(capture)
        git = lambda *args: self.git(*args).encode()
        observed, snapshot = capture.workspace_observation(self.repo, self.sha, {}, git)
        self.assertEqual(observed, {"workspaceState": "clean", "workspaceLockSha256": None})
        self.assertIsNone(snapshot)

    def test_dirty_original_is_rejected_and_never_restored(self):
        file = self.repo / self.paths[-1]
        file.write_text("unrelated active work\n")
        with self.assertRaises(MODULE.IsolationError):
            MODULE.prepare(self.repo, self.runner_temp, self.sha)
        self.assertFalse(self.target.exists())
        self.assertEqual(file.read_text(), "unrelated active work\n")

    def test_original_drift_after_preparation_remains_rejected(self):
        MODULE.prepare(self.repo, self.runner_temp, self.sha)
        file = self.repo / self.paths[-1]
        file.write_text("unexpected original mutation\n")
        with self.assertRaises(MODULE.IsolationError):
            MODULE.verify(self.repo, self.runner_temp, self.sha)
        self.assertEqual(file.read_text(), "unexpected original mutation\n")

    def test_existing_directory_and_symlink_are_not_reused_or_removed(self):
        self.target.mkdir()
        (self.target / "active-work").write_text("preserve")
        with self.assertRaises(MODULE.IsolationError):
            MODULE.prepare(self.repo, self.runner_temp, self.sha)
        self.assertEqual((self.target / "active-work").read_text(), "preserve")
        fresh_runner_temp = self.root / "fresh-runner-temp"
        fresh_runner_temp.mkdir()
        alias = self.root / "runner-alias"
        alias.symlink_to(fresh_runner_temp, target_is_directory=True)
        vacant_target = fresh_runner_temp / MODULE.DIRECTORY
        self.assertFalse(vacant_target.exists())
        with self.assertRaises(MODULE.IsolationError):
            MODULE.prepare(self.repo, alias, self.sha)
        self.assertFalse(vacant_target.exists())
        self.assertTrue(alias.is_symlink())
        self.assertEqual((self.target / "active-work").read_text(), "preserve")

    def test_wrong_head_and_unrelated_repository_are_rejected(self):
        with self.assertRaises(MODULE.IsolationError):
            MODULE.prepare(self.repo, self.runner_temp, "0" * 40)
        subprocess.run(["git", "clone", "--quiet", str(self.repo), str(self.target)], check=True)
        with self.assertRaises(MODULE.IsolationError):
            MODULE.verify(self.repo, self.runner_temp, self.sha)

    def test_attached_branch_is_rejected(self):
        MODULE.prepare(self.repo, self.runner_temp, self.sha)
        self.git("switch", "-c", "fixture-attached", repo=self.target)
        with self.assertRaises(MODULE.IsolationError):
            MODULE.verify(self.repo, self.runner_temp, self.sha)

    def test_nested_output_and_missing_mobile_root_are_rejected(self):
        with self.assertRaises(MODULE.IsolationError):
            MODULE.prepare(self.repo, self.repo, self.sha)
        self.git("rm", "-r", "apps/mobile")
        self.git("-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
                 "commit", "--quiet", "-m", "no mobile", "--no-gpg-sign")
        sha = self.git("rev-parse", "HEAD").strip()
        with self.assertRaises(MODULE.IsolationError):
            MODULE.prepare(self.repo, self.runner_temp, sha)

    def test_hosted_cli_checks_actual_working_directory_and_root(self):
        env = dict(os.environ, GITHUB_ACTIONS="true", GITHUB_JOB="ios-native-acceptance",
                   GITHUB_WORKSPACE=str(self.repo), RUNNER_TEMP=str(self.runner_temp),
                   EXPECTED_HEAD=self.sha, SETTLEORA_IOS_ACCEPTANCE_ROOT=str(self.target))
        command = [sys.executable, "-I", "-S", "-B", str(Path(MODULE.__file__))]
        created = subprocess.run(command, env=env, capture_output=True)
        self.assertEqual(created.returncode, 0, created.stderr)
        verified = subprocess.run(command + ["--verify"], env=env,
                                  cwd=self.target / "apps/mobile", capture_output=True)
        self.assertEqual(verified.returncode, 0, verified.stderr)
        wrong_cwd = subprocess.run(command + ["--verify"], env=env,
                                   cwd=self.repo / "apps/mobile", capture_output=True)
        self.assertEqual(wrong_cwd.returncode, 98)
        env["SETTLEORA_IOS_ACCEPTANCE_ROOT"] = str(self.repo)
        wrong_root = subprocess.run(command + ["--verify"], env=env,
                                    cwd=self.target / "apps/mobile", capture_output=True)
        self.assertEqual(wrong_root.returncode, 98)

    def test_inherited_git_redirection_cannot_escape_fixture_repositories(self):
        external = self.root / "controlled-external"
        external.mkdir()
        self.git("init", "--quiet", repo=external)
        (external / "active-work").write_text("preserve controlled external work\n")
        self.git("add", ".", repo=external)
        self.git("-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
                 "commit", "--quiet", "-m", "external", "--no-gpg-sign", repo=external)
        snapshot = lambda: {str(file.relative_to(external)): file.read_bytes()
                            for file in external.rglob("*") if file.is_file()}
        before = snapshot()
        poisoned = dict(os.environ, GIT_DIR=str(external / ".git"),
                        GIT_WORK_TREE=str(external),
                        GIT_INDEX_FILE=str(external / ".git/index"),
                        GIT_COMMON_DIR=str(external / ".git"),
                        GIT_OBJECT_DIRECTORY=str(external / ".git/objects"),
                        GIT_ALTERNATE_OBJECT_DIRECTORIES=str(external / ".git/objects"),
                        GIT_CONFIG_COUNT="1", GIT_CONFIG_KEY_0="core.hooksPath",
                        GIT_CONFIG_VALUE_0=str(external / "no-hooks"))
        # Read-only control: inherited redirection really does override -C.
        redirected = subprocess.check_output(
            ["git", "--no-optional-locks", "-C", str(self.repo),
             "rev-parse", "--show-toplevel"], env=poisoned, text=True).strip()
        self.assertEqual(redirected, str(external))
        # Exercise fixture setup, in-process prepare/verify and hosted children
        # under poison. Select existing cases so this regression cannot recurse.
        result = subprocess.run(
            [sys.executable, "-I", "-S", "-B", str(Path(__file__).resolve()),
             "IsolationTest.test_exact_detached_source_and_mutations_do_not_dirty_capture_checkout",
             "IsolationTest.test_hosted_cli_checks_actual_working_directory_and_root"],
            env=poisoned, capture_output=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(snapshot(), before)

    def test_prepare_ignores_repository_overrides_but_preserves_git_configuration(self):
        external = self.root / "same-commit-external"
        subprocess.run(["git", "clone", "--quiet", "--no-local", str(self.repo),
                        str(external)], check=True)
        snapshot = lambda: {str(file.relative_to(external)): file.read_bytes()
                            for file in external.rglob("*") if file.is_file()}
        before = snapshot()
        overrides = {"GIT_DIR": str(external / ".git"),
                     "GIT_WORK_TREE": str(self.repo),
                     "GIT_INDEX_FILE": str(external / ".git/index"),
                     "GIT_COMMON_DIR": str(external / ".git"),
                     "GIT_OBJECT_DIRECTORY": str(external / ".git/objects"),
                     "GIT_ALTERNATE_OBJECT_DIRECTORIES": str(external / ".git/objects"),
                     "GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": "settleora.fixtureConfig",
                     "GIT_CONFIG_VALUE_0": "preserved"}
        try:
            with patch.dict(os.environ, overrides):
                target = MODULE.prepare(self.repo, self.runner_temp, self.sha)
                self.assertEqual(MODULE.verify(self.repo, self.runner_temp, self.sha), target)
                self.assertEqual(MODULE.git(target, "config", "--get", "settleora.fixtureConfig"),
                                 b"preserved\n")
            common = ("rev-parse", "--path-format=absolute", "--git-common-dir")
            self.assertEqual(self.git(*common, repo=target), self.git(*common))
        finally:
            self.assertTrue(snapshot() == before, "Controlled external repository changed")

    def test_empty_inherited_object_store_cannot_hide_requested_commit(self):
        empty = self.root / "empty-objects"
        empty.mkdir()
        with patch.dict(os.environ, GIT_OBJECT_DIRECTORY=str(empty),
                        GIT_ALTERNATE_OBJECT_DIRECTORIES=str(empty)):
            inherited = dict(os.environ)
            target = MODULE.prepare(self.repo, self.runner_temp, self.sha)
            self.assertEqual(MODULE.verify(self.repo, self.runner_temp, self.sha), target)
            self.assertEqual(dict(os.environ), inherited)
        self.assertEqual(list(empty.iterdir()), [])
        self.assertEqual(self.git("status", "--porcelain"), "")

    def test_workflow_routes_dependency_verifier_and_runner_to_same_isolated_source(self):
        workflow = (ROOT / ".github/workflows/mobile-ocr-native-acceptance.yml").read_text()
        # Real YAML is parsed by the existing CI policy suite. These checks bind
        # the shell tool's import-relative Podfile.lock lookup to the test copy.
        ios = workflow.split("  ios-native-acceptance:\n", 1)[1]
        self.assertIn("Prepare isolated iOS simulator source", ios)
        self.assertEqual(ios.count("working-directory: ${{ runner.temp }}/ios-acceptance-source/apps/mobile"), 2)
        self.assertIn('node "$RUNNER_TEMP/ios-acceptance-source/tools/ocr-models/verify-ios-test-podfile-lock.mjs"', ios)
        self.assertIn("SETTLEORA_IOS_ACCEPTANCE_ROOT: ${{ runner.temp }}/ios-acceptance-source", ios)
        self.assertLess(ios.index("Prepare isolated iOS simulator source"), ios.index("Install dependencies and pods"))
        runner = (ROOT / "tools/ocr-models/run-ios-native-acceptance.sh").read_text()
        self.assertLess(runner.index('prepare-ios-acceptance-worktree.py" --verify'),
                        runner.index("phase=build_network_isolation"))
        self.assertNotIn('"$GITHUB_WORKSPACE/apps/mobile/', runner)


